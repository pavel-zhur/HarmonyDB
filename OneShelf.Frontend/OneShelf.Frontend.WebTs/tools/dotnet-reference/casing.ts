// Writes src/lib/common/dotnet/invariantCasing.ts from what .NET gives for ToLowerInvariant / ToUpperInvariant of
// every code point (the "chars" case of the reference program):
//   npx vite-node tools/dotnet-reference/casing.ts -- <outputs.jsonl with the chars case>

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const [path] = process.argv.slice(2).filter(x => x !== '--');
if (!path) throw new Error('Usage: casing.ts <outputs.jsonl>');
const line = readFileSync(path, 'utf8').split('\n').find(l => l.includes('"slo":'));
if (!line) throw new Error('No chars case output in the file.');
const out = JSON.parse(line).out as { slo: [number, number][]; stu: [number, number][] };

/** Runs of code points mapped by the same delta, every `step` code points: [start, count, step, delta]. */
function ranges(pairs: [number, number][]): number[][] {
    const result: number[][] = [];
    for (const [cp, mapped] of pairs) {
        const delta = mapped - cp;
        const last = result[result.length - 1];
        if (last) {
            const [start, count, step, lastDelta] = last as [number, number, number, number];
            const end = start + (count - 1) * step;
            if (lastDelta === delta && count === 1 && cp - start <= 2) {
                last[1] = 2;
                last[2] = cp - start;
                continue;
            }

            if (lastDelta === delta && count > 1 && cp === end + step) {
                last[1] = count + 1;
                continue;
            }
        }

        result.push([cp, 1, 1, delta]);
    }

    return result;
}

const format = (items: number[][]) => items.map(x => x.join(',')).join(',\n    ');
const target = fileURLToPath(new URL('../../src/lib/common/dotnet/invariantCasing.ts', import.meta.url));
writeFileSync(target, `// Generated by tools/dotnet-reference/casing.ts from .NET 9 (invariant globalization, as the site runs): the simple
// case mapping string.ToLowerInvariant / ToUpperInvariant applies to each code point. JavaScript's own case mapping
// follows the browser's Unicode version and maps some characters .NET leaves (ı to I, ſ to S, the Greek letters with
// ypogegrammeni), so the site uses this table instead. Do not edit; regenerate.
// Runs of code points: start, count, step, delta (the mapped code point minus the code point).

export const lowerRanges: readonly number[] = [
    ${format(ranges(out.slo))},
];

export const upperRanges: readonly number[] = [
    ${format(ranges(out.stu))},
];
`);
console.log(`Written ${target}: ${ranges(out.slo).length} lower and ${ranges(out.stu).length} upper runs.`);
